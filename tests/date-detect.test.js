test('remindFromText: 첫 줄의 첫 날짜 → 알림 (MagicKey 알림 맞춰 저장)', () => {
  const now = new Date(2026, 10, 6, 10, 0);
  const r = remindFromText('내일 오후 3시 치과\n준비물: 보험증', now);
  assert.deepEqual({ ...r, at: new Date(r.at).getTime() }, { at: new Date(2026, 10, 7, 15, 0).getTime(), hasTime: true, repeat: null, title: '치과' });
  assert.equal(remindFromText('그냥 메모\n내일 3시', now), null, '둘째 줄 날짜는 보지 않는다');
  assert.equal(remindFromText('', now), null);
});

// 기준: 2026-10-10 (토) 오전 10:00
const NOW = new Date(2026, 9, 10, 10, 0);
const fmt = (d) => `${d.getFullYear()}-${d.getMonth() + 1}-${d.getDate()} ${d.getHours()}:${String(d.getMinutes()).padStart(2, '0')}`;
const first = (text, now = NOW) => findDates(text, now)[0] ?? null;

/** [글, 밑줄 칠 말, 시각] 표 — 시각이 null 이면 찾지 않아야 함 */
function table(rows, now = NOW) {
  for (const [text, want, at] of rows) {
    const r = first(text, now);
    if (at === null) {
      assert.equal(r, null, `"${text}" 는 날짜가 아님 (찾음: ${r && `${r.text} → ${fmt(r.at)}`})`);
      continue;
    }
    assert.ok(r, `"${text}" 에서 못 찾음`);
    assert.equal(r.text, want, `"${text}" 밑줄`);
    assert.equal(fmt(r.at), at, `"${text}" 시각`);
  }
}

